CREATE OR REPLACE PROCEDURE update_order_status (
    p_order_id    IN NUMBER,
    p_new_status  IN VARCHAR2,
    p_changed_by  IN NUMBER
)
AS
    v_current_status       VARCHAR2(20);
    v_pickup_window        NUMBER;
    v_previous_identifier  VARCHAR2(64);
BEGIN

    /*
        Preserve the current Oracle session identifier.

        This allows the trigger to know which authenticated
        staff/admin user performed the status transition.
    */

    v_previous_identifier :=
        SYS_CONTEXT(
            'USERENV',
            'CLIENT_IDENTIFIER'
        );


    /*
        Lock the order while changing its status.
    */

    SELECT
        order_status,
        pickup_window_id
    INTO
        v_current_status,
        v_pickup_window
    FROM orders
    WHERE order_id = p_order_id
    FOR UPDATE;


    /*
        Validate requested status.
    */

    IF p_new_status NOT IN (
        'PLACED',
        'PREPARING',
        'READY',
        'COLLECTED'
    )
    THEN

        RAISE_APPLICATION_ERROR(
            -20020,
            'Invalid order status.'
        );

    END IF;


    /*
        Prevent invalid backward or skipped transitions.
    */

    IF v_current_status = 'PLACED'
       AND p_new_status <> 'PREPARING'
    THEN

        RAISE_APPLICATION_ERROR(
            -20021,
            'PLACED orders can only move to PREPARING.'
        );


    ELSIF v_current_status = 'PREPARING'
       AND p_new_status <> 'READY'
    THEN

        RAISE_APPLICATION_ERROR(
            -20022,
            'PREPARING orders can only move to READY.'
        );


    ELSIF v_current_status = 'READY'
       AND p_new_status <> 'COLLECTED'
    THEN

        RAISE_APPLICATION_ERROR(
            -20023,
            'READY orders can only move to COLLECTED.'
        );


    ELSIF v_current_status IN (
        'COLLECTED',
        'CANCELLED'
    )
    THEN

        RAISE_APPLICATION_ERROR(
            -20024,
            'Completed or cancelled orders cannot change status.'
        );

    END IF;


    /*
        Set the authenticated actor for the trigger.

        CLIENT_IDENTIFIER is session-scoped and does not
        require a custom application context.
    */

    DBMS_SESSION.SET_IDENTIFIER(
        TO_CHAR(p_changed_by)
    );


    /*
        Update the order status.

        The status-history trigger fires here and reads
        CLIENT_IDENTIFIER as CHANGED_BY.
    */

    UPDATE orders
    SET order_status = p_new_status
    WHERE order_id = p_order_id;


    /*
        When the order is collected, release its
        pickup-window reservation.

        Stock is NOT restored because the food has
        already been fulfilled.
    */

    IF p_new_status = 'COLLECTED' THEN

        UPDATE pickup_windows
        SET reserved_count =
            CASE
                WHEN reserved_count > 0
                THEN reserved_count - 1
                ELSE 0
            END
        WHERE pickup_window_id = v_pickup_window;

    END IF;


    /*
        Restore the previous session identifier before
        committing the transaction.
    */

    DBMS_SESSION.SET_IDENTIFIER(
        v_previous_identifier
    );


    COMMIT;


EXCEPTION

    WHEN NO_DATA_FOUND THEN

        ROLLBACK;

        DBMS_SESSION.SET_IDENTIFIER(
            v_previous_identifier
        );

        RAISE_APPLICATION_ERROR(
            -20025,
            'Order not found.'
        );


    WHEN OTHERS THEN

        ROLLBACK;

        DBMS_SESSION.SET_IDENTIFIER(
            v_previous_identifier
        );

        RAISE;

END;
